type CsKey = Parameters<typeof cs>[0];
const has = (k: string): k is CsKey => (cs.keys as readonly string[]).includes(k);

/** Label of a driver-specific field (`sslmode` → SSL 모드); unknown keys show as-is. */
export function fieldLabel(key: string): string {
  const k = `field.${key}`;
  return has(k) ? cs(k) : key;
}

/** Label of one registry choice (`protocol` + `legacy` → MySQL 3.23–4.0 (4.1 이전)); else the raw value. */
export function choiceLabel(field: string, value: string): string {
  const k = `choice.${field}.${value}`;
  return has(k) ? cs(k) : value;
}

/** Warning / help line under a driver field (`hint.allow_old_password`), if any. */
export function fieldHint(field: string): string | undefined {
  const k = `hint.${field}`;
  return has(k) ? cs(k) : undefined;
}
