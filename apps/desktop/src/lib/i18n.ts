const maps: Record<Lang, Record<I18nKey, string>> = { en, ko };

let currentLang: Lang = 'ko';

export function getLang(): Lang {
  return currentLang;
}

export function setLang(lang: Lang): void {
  currentLang = lang;
}

/** Translate `key`, substituting `{name}` placeholders from `params`. */
export function t(key: I18nKey, params?: Record<string, string | number>): string {
  let s: string = maps[currentLang][key] ?? en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

/** Label for a job state (one of the nine). */
export function stateLabel(state: string): string {
  return t(`state.${state}` as I18nKey);
}

/** Label for a job phase. */
export function phaseLabel(phase: string): string {
  return t(`phase.${phase}` as I18nKey);
}
