//! `cargo test -p bulk-core --features ts-export export_bindings` regenerates
//! `packages/ipc-types/src/generated/*.ts` + `index.ts`. CI's typegen-check fails when the
//! committed output differs.

use ts_rs::TS;

use crate::error::ErrorPayload;
use crate::sqlguard::{SqlCheck, StatementKind};
use crate::types::*;

macro_rules! export_all {
    ($dir:expr, $($t:ty),* $(,)?) => {
        $( <$t as TS>::export_all_to($dir).expect(concat!("export ", stringify!($t))); )*
    };
}

#[test]
fn export_bindings() {
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packages/ipc-types/src/generated");
    std::fs::create_dir_all(&dir).unwrap();
    for entry in std::fs::read_dir(&dir).unwrap().flatten() {
        if entry.path().extension().map(|e| e == "ts").unwrap_or(false) {
            std::fs::remove_file(entry.path()).unwrap();
        }
    }
    export_all!(
        &dir,
        ErrorPayload,
        Connection,
        ConnectionInput,
        SshConfig,
        SshAuth,
        SessionOpts,
        OutputFormat,
        CsvOpts,
        ParquetOpts,
        ParquetCompression,
        Compression,
        SplitOpts,
        OutputOpts,
        ExportRequest,
        ServerInfo,
        ProbeResult,
        TableRef,
        DatabaseInfo,
        SchemaInfo,
        TableKind,
        TableInfo,
        ColumnInfo,
        IndexInfo,
        ExactCount,
        Severity,
        PlanWarning,
        PlanNode,
        PlanSummary,
        PreflightIssue,
        PreflightEstimates,
        SessionInfo,
        PreflightReport,
        JobKind,
        JobState,
        JobPhase,
        JobProgress,
        Bottleneck,
        JobServer,
        JobResult,
        JobDone,
        JobStateEvent,
        JobSummary,
        LogLevel,
        LogEvent,
        HistoryEntry,
        Settings,
        DriverTier,
        DriverInfo,
        HostKeyPrompt,
        SshPasswordPrompt,
        SqlFile,
        ImportedConnection,
        DiagnosticsBundle,
        AppInfo,
        StatementKind,
        SqlCheck,
        CoreEvent,
    );
    // index.ts re-exporting every generated file, sorted for stable diffs.
    let mut names: Vec<String> = std::fs::read_dir(&dir)
        .unwrap()
        .flatten()
        .filter_map(|e| {
            let p = e.path();
            let stem = p.file_stem()?.to_str()?.to_string();
            if p.extension()? == "ts" && stem != "index" {
                Some(stem)
            } else {
                None
            }
        })
        .collect();
    names.sort();
    let mut index = String::from("// Generated by `pnpm typegen` (ts-rs). Do not edit by hand.\n");
    for n in names {
        index.push_str(&format!("export type {{ {n} }} from \"./{n}\";\n"));
    }
    std::fs::write(dir.join("index.ts"), index).unwrap();
}
