//! PostgreSQL statement builders (3.5). The catalog is read with the pretty `pg_get_*def`
//! variants under `SET search_path = <schema>, pg_catalog`, so names of the copied schema come
//! unqualified and every DDL statement runs under `SET search_path = <target schema>,
//! pg_catalog` (that is how a schema rename works). Only the object being created is qualified
//! here, with the target schema.

use super::{dq, dq2, pg_str};

/// `SET search_path = "s", pg_catalog`.
pub fn search_path(schema: &str) -> String {
    format!("SET search_path = {}, pg_catalog", dq(schema))
}

/// A column of `CREATE TABLE`.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct PgColumnDef {
    pub name: String,
    /// `format_type` output.
    pub type_sql: String,
    /// `"schema"."collation"` when it differs from the type's default.
    pub collation: Option<String>,
    pub default: Option<String>,
    pub not_null: bool,
    /// PG18 named NOT NULL constraint (written only on 18+ targets).
    pub not_null_name: Option<String>,
    /// `a` (ALWAYS) / `d` (BY DEFAULT).
    pub identity: Option<char>,
    /// The identity's sequence: (qualified target name, options).
    pub identity_seq: Option<(String, PgSeqOptions)>,
    /// `GENERATED ALWAYS AS (expr) STORED` (`attgenerated = 's'`), or VIRTUAL with
    /// `generated_virtual`.
    pub generated: Option<String>,
    /// PG18 virtual generated column (`attgenerated = 'v'`): `VIRTUAL` on 18+ targets, `STORED`
    /// below (the planner adds `DOWNGRADE`).
    pub generated_virtual: bool,
}

/// Sequence options from `pg_sequence`.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct PgSeqOptions {
    pub type_sql: String,
    pub start: i128,
    pub increment: i128,
    pub min: i128,
    pub max: i128,
    pub cache: i128,
    pub cycle: bool,
}

impl PgSeqOptions {
    fn body(&self, with_type: bool) -> String {
        let mut s = String::new();
        if with_type && !self.type_sql.is_empty() {
            s.push_str(&format!("AS {} ", self.type_sql));
        }
        s.push_str(&format!("START WITH {} INCREMENT BY {} MINVALUE {} MAXVALUE {} CACHE {}", self.start, self.increment, self.min, self.max, self.cache));
        if self.cycle {
            s.push_str(" CYCLE");
        }
        s
    }
}

/// `CREATE SEQUENCE "s"."q" AS bigint START WITH … CACHE 1 [CYCLE]`.
pub fn create_sequence(qualified: &str, o: &PgSeqOptions) -> String {
    format!("CREATE SEQUENCE {qualified} {}", o.body(true))
}

/// One column definition.
pub fn column_sql(c: &PgColumnDef, target_major: u16) -> String {
    let mut s = format!("{} {}", dq(&c.name), c.type_sql);
    if let Some(coll) = &c.collation {
        s.push_str(&format!(" COLLATE {coll}"));
    }
    if let Some(expr) = &c.generated {
        let how = if c.generated_virtual && target_major >= 18 { "VIRTUAL" } else { "STORED" };
        s.push_str(&format!(" GENERATED ALWAYS AS ({expr}) {how}"));
    } else if let Some(kind) = c.identity {
        s.push_str(if kind == 'a' { " GENERATED ALWAYS AS IDENTITY" } else { " GENERATED BY DEFAULT AS IDENTITY" });
        if let Some((name, o)) = &c.identity_seq {
            s.push_str(&format!(" (SEQUENCE NAME {name} {})", o.body(false)));
        }
    } else if let Some(d) = &c.default {
        s.push_str(&format!(" DEFAULT {d}"));
    }
    if c.not_null {
        match &c.not_null_name {
            Some(n) if target_major >= 18 => s.push_str(&format!(" CONSTRAINT {} NOT NULL", dq(n))),
            _ => s.push_str(" NOT NULL"),
        }
    }
    s
}

/// What `CREATE TABLE` needs besides the columns.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct PgTableDef {
    pub unlogged: bool,
    pub columns: Vec<PgColumnDef>,
    /// `CONSTRAINT "c" CHECK (…)` items (validated, local).
    pub constraints: Vec<String>,
    /// `INHERITS (…)` parents, already quoted.
    pub inherits: Vec<String>,
    /// `pg_get_partkeydef` output.
    pub partition_by: Option<String>,
    /// `PARTITION OF "parent" FOR VALUES …`: (parent quoted, bound).
    pub partition_of: Option<(String, String)>,
    /// `reloptions` (`fillfactor=70`).
    pub reloptions: Vec<String>,
}

/// `CREATE [UNLOGGED] TABLE "t" (…) [INHERITS (…)] [PARTITION BY …] [WITH (…)]`, or
/// `CREATE TABLE "t" PARTITION OF "p" [(…constraints)] FOR VALUES …`.
pub fn create_table(name: &str, t: &PgTableDef, target_major: u16) -> String {
    let head = format!("CREATE {}TABLE {name}", if t.unlogged { "UNLOGGED " } else { "" });
    let mut s;
    if let Some((parent, bound)) = &t.partition_of {
        s = format!("{head} PARTITION OF {parent}");
        if !t.constraints.is_empty() {
            s.push_str(&format!(" (\n    {}\n)", t.constraints.join(",\n    ")));
        }
        s.push_str(&format!(" {bound}"));
    } else {
        let mut body: Vec<String> = t.columns.iter().map(|c| column_sql(c, target_major)).collect();
        body.extend(t.constraints.iter().cloned());
        s = format!("{head} (\n    {}\n)", body.join(",\n    "));
        if !t.inherits.is_empty() {
            s.push_str(&format!(" INHERITS ({})", t.inherits.join(", ")));
        }
    }
    if let Some(pb) = &t.partition_by {
        s.push_str(&format!(" PARTITION BY {pb}"));
    }
    if !t.reloptions.is_empty() {
        s.push_str(&format!(" WITH ({})", t.reloptions.join(", ")));
    }
    s
}

/// `CREATE TYPE "t" AS ENUM ('a', 'b')`.
pub fn create_enum(name: &str, labels: &[String]) -> String {
    format!("CREATE TYPE {name} AS ENUM ({})", labels.iter().map(|l| pg_str(l)).collect::<Vec<_>>().join(", "))
}

/// `CREATE DOMAIN "d" AS base [COLLATE c] [DEFAULT …] [NOT NULL] [CONSTRAINT … CHECK (…)]…`.
pub fn create_domain(name: &str, base: &str, collation: Option<&str>, default: Option<&str>, not_null: bool, checks: &[(String, String)]) -> String {
    let mut s = format!("CREATE DOMAIN {name} AS {base}");
    if let Some(c) = collation {
        s.push_str(&format!(" COLLATE {c}"));
    }
    if let Some(d) = default {
        s.push_str(&format!(" DEFAULT {d}"));
    }
    if not_null {
        s.push_str(" NOT NULL");
    }
    for (n, def) in checks {
        s.push_str(&format!(" CONSTRAINT {} {def}", dq(n)));
    }
    s
}

/// `CREATE TYPE "t" AS ("a" int, "b" text COLLATE "C")`.
pub fn create_composite(name: &str, attrs: &[(String, String, Option<String>)]) -> String {
    let body: Vec<String> = attrs.iter().map(|(n, t, c)| format!("{} {t}{}", dq(n), c.as_ref().map(|c| format!(" COLLATE {c}")).unwrap_or_default())).collect();
    format!("CREATE TYPE {name} AS ({})", body.join(", "))
}

/// `CREATE TYPE "r" AS RANGE (SUBTYPE = …[, SUBTYPE_DIFF = …])`.
pub fn create_range(name: &str, subtype: &str, diff: Option<&str>) -> String {
    match diff {
        Some(d) => format!("CREATE TYPE {name} AS RANGE (SUBTYPE = {subtype}, SUBTYPE_DIFF = {d})"),
        None => format!("CREATE TYPE {name} AS RANGE (SUBTYPE = {subtype})"),
    }
}

/// `CREATE COLLATION` from `to_jsonb(pg_collation)` (works across 10-18 column changes).
pub fn create_collation(name: &str, j: &serde_json::Value) -> Option<String> {
    let s = |k: &str| j.get(k).and_then(|v| v.as_str()).filter(|v| !v.is_empty()).map(str::to_string);
    let provider = s("collprovider").unwrap_or_else(|| "c".into());
    let deterministic = j.get("collisdeterministic").and_then(|v| v.as_bool()).unwrap_or(true);
    let mut opts: Vec<String> = Vec::new();
    match provider.as_str() {
        "i" => {
            opts.push("provider = icu".into());
            let loc = s("colllocale").or_else(|| s("colliculocale")).or_else(|| s("collcollate"))?;
            opts.push(format!("locale = {}", pg_str(&loc)));
            if let Some(r) = s("collicurules") {
                opts.push(format!("rules = {}", pg_str(&r)));
            }
        }
        "b" => {
            opts.push("provider = builtin".into());
            opts.push(format!("locale = {}", pg_str(&s("colllocale")?)));
        }
        "d" => return None,
        _ => {
            opts.push("provider = libc".into());
            opts.push(format!("lc_collate = {}", pg_str(&s("collcollate")?)));
            opts.push(format!("lc_ctype = {}", pg_str(&s("collctype")?)));
        }
    }
    if !deterministic {
        opts.push("deterministic = false".into());
    }
    Some(format!("CREATE COLLATION {name} ({})", opts.join(", ")))
}

/// `pg_get_functiondef` qualifies the function's own name: the header becomes
/// `CREATE FUNCTION "<target schema>"."f"(` (and `OR REPLACE` is dropped, so an object the plan
/// did not see is never replaced). `qname` is the source's `quote_ident(nsp).quote_ident(name)`.
pub fn rewrite_function_header(def: &str, qname: &str, target_qualified: &str) -> String {
    let def = def.trim_end();
    for kw in ["FUNCTION", "PROCEDURE"] {
        let from = format!("CREATE OR REPLACE {kw} {qname}(");
        if let Some(rest) = def.strip_prefix(&from) {
            return format!("CREATE {kw} {target_qualified}({rest}");
        }
    }
    def.replacen("CREATE OR REPLACE ", "CREATE ", 1)
}

/// The statement that restores a trigger's `tgenabled` state (`O` needs none).
pub fn trigger_enable_sql(table: &str, trigger: &str, enabled: &str) -> Option<String> {
    match enabled {
        "D" => Some(format!("ALTER TABLE {table} DISABLE TRIGGER {}", dq(trigger))),
        "R" => Some(format!("ALTER TABLE {table} ENABLE REPLICA TRIGGER {}", dq(trigger))),
        "A" => Some(format!("ALTER TABLE {table} ENABLE ALWAYS TRIGGER {}", dq(trigger))),
        _ => None,
    }
}

/// `CREATE POLICY "p" ON "t" AS PERMISSIVE FOR ALL TO r USING (…) WITH CHECK (…)`.
pub fn create_policy(name: &str, table: &str, permissive: bool, cmd: &str, roles: &[String], qual: Option<&str>, check: Option<&str>) -> String {
    let cmd = match cmd {
        "r" => "SELECT",
        "a" => "INSERT",
        "w" => "UPDATE",
        "d" => "DELETE",
        _ => "ALL",
    };
    let mut s = format!("CREATE POLICY {} ON {table} AS {} FOR {cmd}", dq(name), if permissive { "PERMISSIVE" } else { "RESTRICTIVE" });
    if !roles.is_empty() {
        s.push_str(&format!(" TO {}", roles.join(", ")));
    }
    if let Some(q) = qual {
        s.push_str(&format!(" USING ({q})"));
    }
    if let Some(c) = check {
        s.push_str(&format!(" WITH CHECK ({c})"));
    }
    s
}

/// `CREATE [MATERIALIZED] VIEW "v" [WITH (…)] AS <def> [WITH NO DATA]`.
pub fn create_view(name: &str, materialized: bool, reloptions: &[String], def: &str) -> String {
    let body = def.trim().trim_end_matches(';').trim_end();
    let with = if reloptions.is_empty() { String::new() } else { format!(" WITH ({})", reloptions.join(", ")) };
    if materialized {
        format!("CREATE MATERIALIZED VIEW {name}{with} AS\n{body}\nWITH NO DATA")
    } else {
        format!("CREATE VIEW {name}{with} AS\n{body}")
    }
}

/// `pg_get_indexdef` for the target: an index on a partitioned table is created on the whole
/// tree (`ON ONLY` would leave it invalid, because partition indexes are not copied).
pub fn index_sql(def: &str, partitioned: bool) -> String {
    if partitioned {
        def.replacen(" ON ONLY ", " ON ", 1)
    } else {
        def.to_string()
    }
}

/// `"s"."t"` for a target object.
pub fn qualified(schema: &str, name: &str) -> String {
    dq2(schema, name)
}

/// The source database's default collation as a collation that exists on the target by name
/// (`target`: its `(schema, name)` pairs), for text partition keys (3.5). Only libc defaults
/// (`provider` `c`, or unknown before PG 15) are mapped: `C` / `POSIX` always exist, other
/// locales match a `pg_catalog` collation whose name equals `datcollate` ignoring case and `-`
/// (`en_US.UTF-8` -> `"en_US.utf8"`). ICU and builtin defaults are not mapped (`None`).
pub fn named_default_collation(datcollate: &str, provider: Option<&str>, target: &std::collections::BTreeSet<(String, String)>) -> Option<String> {
    if provider.is_some_and(|p| !p.is_empty() && p != "c") {
        return None;
    }
    let d = datcollate.trim();
    if d.eq_ignore_ascii_case("C") || d.eq_ignore_ascii_case("POSIX") {
        return Some(format!("pg_catalog.{}", dq(&d.to_ascii_uppercase())));
    }
    let norm = |s: &str| s.to_ascii_lowercase().replace('-', "");
    let want = norm(d);
    if want.is_empty() {
        return None;
    }
    target.iter().find(|(schema, name)| schema == "pg_catalog" && norm(name) == want).map(|(_, name)| format!("pg_catalog.{}", dq(name)))
}

/// `pg_get_partkeydef` output with an explicit `COLLATE` added to each key element `i` for which
/// `collations[i]` is set and that has none yet (pg_get_partkeydef omits a key's collation when
/// it is the column's, e.g. the database default, so the target would route text keys by its
/// own default collation, 3.5). The `COLLATE` goes right after the column or expression, before
/// an operator class: `RANGE (name text_pattern_ops)` -> `RANGE (name COLLATE "C" text_pattern_ops)`.
pub fn partkey_with_collations(partkey: &str, collations: &[Option<String>]) -> String {
    let (Some(open), Some(close)) = (partkey.find('('), partkey.rfind(')')) else { return partkey.to_string() };
    if close <= open {
        return partkey.to_string();
    }
    let inner = &partkey[open + 1..close];
    let elems = split_top_level(inner);
    let out: Vec<String> = elems
        .iter()
        .enumerate()
        .map(|(i, e)| {
            let e = e.trim();
            match collations.get(i).cloned().flatten() {
                Some(coll) if !e.to_ascii_uppercase().contains(" COLLATE ") => {
                    let end = key_term_end(e);
                    let (term, rest) = e.split_at(end);
                    if rest.trim().is_empty() {
                        format!("{term} COLLATE {coll}")
                    } else {
                        format!("{term} COLLATE {coll} {}", rest.trim())
                    }
                }
                _ => e.to_string(),
            }
        })
        .collect();
    format!("{}({}){}", &partkey[..open], out.join(", "), &partkey[close + 1..])
}

/// Split at commas outside parentheses and quotes.
fn split_top_level(s: &str) -> Vec<&str> {
    let mut out = Vec::new();
    let (mut depth, mut start) = (0i32, 0usize);
    let (mut dq_open, mut sq_open) = (false, false);
    for (i, c) in s.char_indices() {
        match c {
            '"' if !sq_open => dq_open = !dq_open,
            '\'' if !dq_open => sq_open = !sq_open,
            '(' if !dq_open && !sq_open => depth += 1,
            ')' if !dq_open && !sq_open => depth -= 1,
            ',' if depth == 0 && !dq_open && !sq_open => {
                out.push(&s[start..i]);
                start = i + 1;
            }
            _ => {}
        }
    }
    out.push(&s[start..]);
    out
}

/// End of the column or expression that starts a partition key element: a parenthesised
/// expression, or a (possibly qualified, possibly quoted) name, followed by a call's argument
/// list when there is one.
fn key_term_end(e: &str) -> usize {
    let b = e.as_bytes();
    let matching = |from: usize| -> usize {
        let (mut depth, mut i, mut quoted) = (0i32, from, false);
        while i < b.len() {
            match b[i] {
                b'"' => quoted = !quoted,
                b'(' if !quoted => depth += 1,
                b')' if !quoted => {
                    depth -= 1;
                    if depth == 0 {
                        return i + 1;
                    }
                }
                _ => {}
            }
            i += 1;
        }
        b.len()
    };
    if b.first() == Some(&b'(') {
        return matching(0);
    }
    let mut i = 0;
    while i < b.len() {
        if b[i] == b'"' {
            i += 1;
            while i < b.len() {
                if b[i] == b'"' {
                    if b.get(i + 1) == Some(&b'"') {
                        i += 2;
                        continue;
                    }
                    break;
                }
                i += 1;
            }
            i += 1;
        } else if b[i].is_ascii_alphanumeric() || b[i] == b'_' || b[i] == b'.' || b[i] == b'$' || b[i] >= 0x80 {
            i += 1;
        } else {
            break;
        }
    }
    if b.get(i) == Some(&b'(') {
        return matching(i);
    }
    i.min(b.len())
}

