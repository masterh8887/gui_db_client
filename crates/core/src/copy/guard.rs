//! Target statement allow-lists (section 5.2). Every statement the executor sends to a copy
//! target passes [`check_statement`] (writes) or [`check_read`] (reads); nothing else ever runs
//! on a target. Owner: copy-data.
//!
//! * Exactly one statement (`sqlguard::split_statements_compound(sql, dialect).len() == 1`: the
//!   family's lexing rules; a trigger or routine body stays with its CREATE).
//! * A leading keyword allowed for the family and, for drops / truncates / deletes, the item's
//!   action (drop_recreate / truncate items only).
//! * Always rejected: `SET GLOBAL`, `SET PERSIST[_ONLY]`, `SET @@global.`, account / role SETs
//!   (`SET PASSWORD`, `SET DEFAULT ROLE`, `SET ROLE`, `SET SESSION AUTHORIZATION`, `SET RESOURCE
//!   GROUP`), `DROP DATABASE`, `DROP SCHEMA`, `DROP EXTENSION`, `DELETE` / `UPDATE` other than
//!   the SQLite shapes, `KILL`, server-level `ALTER SYSTEM | ROLE | USER | DATABASE | TABLESPACE
//!   | SERVER | INSTANCE` and `CREATE USER | ROLE | TABLESPACE | SERVER`.
//! * The session context (`plan.session_sql.target`, prelude, foreign_key_checks) is limited to
//!   `SET` (session scope, after the always-rejected filter) and transaction control: no CREATE
//!   / ALTER / DROP there. TRUNCATE is only a `(Table, Truncate)` or `(TruncateGroup, Run)` item,
//!   SQLite DELETE only a `(Table, Truncate)` item; neither is ever sent in the load context.
//! * Dry runs on PostgreSQL have their own narrower list (CREATE, ALTER, COMMENT ON, GRANT,
//!   SET, transaction control).

use crate::copy::types::{CopyFamily, CopyObjectKind, PlanAction};
use crate::error::{CoreError, Result};
use crate::sqlguard;

/// Why a statement is sent.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum StmtContext {
    /// A `target_sql` statement of a plan item.
    Item { kind: CopyObjectKind, action: PlanAction },
    /// Session settings (`plan.session_sql.target`) and transaction control.
    Session,
    /// A load statement generated by a writer (`COPY … FROM STDIN`, `LOAD DATA`, `INSERT`).
    Load,
    /// The target lease (`pg_try_advisory_lock`, `GET_LOCK`).
    Lease,
    /// A PostgreSQL dry run (rolled back).
    DryRun,
}

/// The first `n` words of `sql` in upper case, skipping whitespace, `--` and `/* */` comments;
/// MySQL executable comments (`/*!50001 … */`) are transparent: their content counts.
pub fn leading_words(sql: &str, n: usize) -> Vec<String> {
    let b = sql.as_bytes();
    let mut i = 0;
    let mut out = Vec::new();
    while i < b.len() && out.len() < n {
        let c = b[i];
        if c.is_ascii_whitespace() || c == b'(' {
            i += 1;
        } else if b[i..].starts_with(b"--") {
            while i < b.len() && b[i] != b'\n' {
                i += 1;
            }
        } else if b[i..].starts_with(b"/*!") {
            i += 3;
            while i < b.len() && b[i].is_ascii_digit() {
                i += 1;
            }
        } else if b[i..].starts_with(b"*/") {
            i += 2;
        } else if b[i..].starts_with(b"/*") {
            match sql[i + 2..].find("*/") {
                Some(end) => i += end + 4,
                None => i = b.len(),
            }
        } else {
            let start = i;
            while i < b.len() && (b[i].is_ascii_alphanumeric() || b[i] == b'_' || b[i] == b'@' || b[i] == b'.') {
                i += 1;
            }
            if i == start {
                // Punctuation (a quoted identifier, `=`): the word list ends here.
                break;
            }
            out.push(sql[start..i].to_ascii_uppercase());
        }
    }
    out
}

fn reject(sql: &str, why: &str) -> CoreError {
    let head: String = sql.trim().chars().take(80).collect();
    CoreError::Internal(format!("copy: refused target statement ({why}): {head}"))
}

/// Single statement, or `INTERNAL`. Lexed with the family's rules (MySQL: backslash escapes);
/// a trigger or routine body (`BEGIN … END` of SQLite / MySQL triggers, PostgreSQL `BEGIN
/// ATOMIC`) belongs to its statement (`sqlguard::split_statements_compound`).
fn one_statement(family: CopyFamily, sql: &str) -> Result<()> {
    let dialect = if family == CopyFamily::Mysql { sqlguard::Dialect::MySql } else { sqlguard::Dialect::Standard };
    if sqlguard::split_statements_compound(sql, dialect).len() != 1 {
        return Err(reject(sql, "not exactly one statement"));
    }
    Ok(())
}

/// Statements no context may ever send.
pub fn check_always_rejected(sql: &str) -> Result<()> {
    let w = leading_words(sql, 4);
    let w: Vec<&str> = w.iter().map(String::as_str).collect();
    let bad = match w.as_slice() {
        ["SET", "GLOBAL", ..] | ["SET", "PERSIST", ..] | ["SET", "PERSIST_ONLY", ..] => true,
        ["SET", x, ..] if x.starts_with("@@GLOBAL.") || x.starts_with("@@PERSIST") => true,
        // Account / role changes dressed up as a SET (never a session setting the copy needs).
        ["SET", "PASSWORD", ..] | ["SET", "ROLE", ..] | ["SET", "DEFAULT", "ROLE", ..] | ["SET", "SESSION", "AUTHORIZATION", ..] | ["SET", "RESOURCE", "GROUP", ..] => {
            true
        }
        ["DROP", "DATABASE" | "SCHEMA" | "EXTENSION", ..] => true,
        ["KILL", ..] => true,
        ["ALTER", "SYSTEM" | "ROLE" | "USER" | "DATABASE" | "TABLESPACE" | "SERVER" | "INSTANCE", ..] => true,
        ["CREATE", "USER" | "ROLE" | "TABLESPACE" | "SERVER", ..] => true,
        _ => false,
    };
    // `SET x = 1, GLOBAL y = 2` (MySQL) hides a global assignment after the first variable.
    let upper = sql.to_ascii_uppercase();
    let hidden_global = w.first() == Some(&"SET") && (upper.contains("@@GLOBAL.") || upper.contains(", GLOBAL ") || upper.contains(",GLOBAL "));
    if bad || hidden_global {
        return Err(reject(sql, "never allowed"));
    }
    Ok(())
}

fn is_tx_control(w: &[&str]) -> bool {
    matches!(w, ["BEGIN", ..] | ["START", "TRANSACTION", ..] | ["COMMIT", ..] | ["ROLLBACK", ..] | ["SAVEPOINT", ..] | ["RELEASE", ..])
}

/// `DELETE FROM "t"` / `DELETE FROM "main"."t"` without anything after the name.
fn sqlite_delete_all(sql: &str) -> bool {
    let re = regex::Regex::new(r#"(?is)^\s*DELETE\s+FROM\s+(?:"(?:[^"]|"")+"\s*\.\s*)?"(?:[^"]|"")+"\s*;?\s*$"#).expect("regex");
    re.is_match(sql)
}

fn ends_with_restrict(sql: &str) -> bool {
    let t = sql.trim().trim_end_matches(';').trim_end();
    t.len() >= 8 && t[t.len() - 8..].eq_ignore_ascii_case("RESTRICT")
}

/// Check one write statement for `family` in `ctx` (5.2).
pub fn check_statement(family: CopyFamily, sql: &str, ctx: StmtContext) -> Result<()> {
    one_statement(family, sql)?;
    check_always_rejected(sql)?;
    let words = leading_words(sql, 5);
    let w: Vec<&str> = words.iter().map(String::as_str).collect();
    if w.is_empty() {
        return Err(reject(sql, "empty statement"));
    }
    if ctx == StmtContext::DryRun {
        let ok = family == CopyFamily::Postgres
            && (matches!(
                w.as_slice(),
                ["CREATE", ..]
                    | ["ALTER", ..]
                    | ["COMMENT", "ON", ..]
                    | ["GRANT", ..]
                    | ["SET", ..]
                    | ["BEGIN", ..]
                    | ["SAVEPOINT", ..]
                    | ["RELEASE", ..]
                    | ["ROLLBACK", ..]
            ) && !matches!(w.as_slice(), ["CREATE", "DATABASE", ..]));
        return if ok { Ok(()) } else { Err(reject(sql, "not allowed in a dry run")) };
    }
    if is_tx_control(&w) {
        return Ok(());
    }
    // Session settings: only `SET` (session scope; the dangerous SETs were rejected above) and
    // transaction control (handled above). No CREATE / ALTER / DROP on a session.
    if ctx == StmtContext::Session {
        return if matches!(w.as_slice(), ["SET", ..]) { Ok(()) } else { Err(reject(sql, "only SET and transaction control in a session context")) };
    }
    let action = match ctx {
        StmtContext::Item { action, .. } => Some(action),
        _ => None,
    };
    let kind = match ctx {
        StmtContext::Item { kind, .. } => Some(kind),
        _ => None,
    };
    let drop_allowed = action == Some(PlanAction::DropRecreate);
    let ok = match w.as_slice() {
        ["SET", ..] => true,
        ["CREATE", "DATABASE", ..] | ["CREATE", "SCHEMA", ..] if family == CopyFamily::Mysql => kind == Some(CopyObjectKind::Database),
        ["CREATE", "DATABASE", ..] => false,
        ["CREATE", ..] | ["ALTER", ..] => true,
        ["DROP", obj, ..] => {
            drop_allowed
                && match family {
                    CopyFamily::Postgres => {
                        matches!(
                            *obj,
                            "TABLE" | "VIEW" | "MATERIALIZED" | "FUNCTION" | "PROCEDURE" | "TYPE" | "DOMAIN" | "SEQUENCE" | "INDEX" | "TRIGGER" | "POLICY" | "COLLATION"
                        ) && ends_with_restrict(sql)
                    }
                    CopyFamily::Mysql => matches!(*obj, "TABLE" | "VIEW" | "TRIGGER"),
                    CopyFamily::Sqlite => matches!(*obj, "TABLE" | "VIEW" | "TRIGGER" | "INDEX"),
                }
        }
        ["TRUNCATE", ..] => {
            // Only a table-truncate item or a truncate-group item; never on a load session or any
            // other item (an Analyze / Comment / Create item must not carry a TRUNCATE).
            matches!(family, CopyFamily::Postgres | CopyFamily::Mysql)
                && matches!((kind, action), (Some(CopyObjectKind::Table), Some(PlanAction::Truncate)) | (Some(CopyObjectKind::TruncateGroup), Some(PlanAction::Run)))
                && (family != CopyFamily::Mysql || matches!(w.get(1), Some(&"TABLE")))
        }
        ["COPY", ..] => family == CopyFamily::Postgres && sql.to_ascii_uppercase().contains("FROM STDIN"),
        ["COMMENT", "ON", ..] | ["GRANT", ..] | ["REFRESH", "MATERIALIZED", "VIEW", ..] => family == CopyFamily::Postgres,
        ["ANALYZE", ..] => true,
        ["SELECT", f, ..] => match family {
            CopyFamily::Postgres => {
                let up = sql.to_ascii_uppercase();
                let t = up.trim_start();
                *f == "PG_CATALOG.SETVAL" || t.starts_with("SELECT PG_CATALOG.SETVAL(") || t.starts_with("SELECT PG_TRY_ADVISORY_LOCK(")
            }
            CopyFamily::Mysql => sql.trim_start().to_ascii_uppercase().starts_with("SELECT GET_LOCK("),
            CopyFamily::Sqlite => false,
        },
        ["LOAD", "DATA", "LOCAL", "INFILE", ..] => family == CopyFamily::Mysql && sql.contains("INFILE 'bulkdb-"),
        ["INSERT", "INTO", ..] => match family {
            CopyFamily::Mysql => true,
            CopyFamily::Sqlite => {
                let t = sql.trim_start();
                let rest = t[6..].trim_start()[4..].trim_start();
                rest.starts_with('"') || rest.to_ascii_lowercase().starts_with("sqlite_sequence")
            }
            CopyFamily::Postgres => false,
        },
        // SQLite empties a table with `DELETE FROM "t"`; only a table-truncate item, never a load.
        ["DELETE", ..] => family == CopyFamily::Sqlite && matches!((kind, action), (Some(CopyObjectKind::Table), Some(PlanAction::Truncate))) && sqlite_delete_all(sql),
        ["UPDATE", "SQLITE_SEQUENCE", ..] => family == CopyFamily::Sqlite && sql.to_ascii_lowercase().replace(' ', "").contains("setseq=max(seq,"),
        _ => false,
    };
    if ok {
        Ok(())
    } else {
        Err(reject(sql, "keyword not allowed for this family or item"))
    }
}

/// Target reads (`query_meta`, `count_rows`, probes, `SHOW WARNINGS`, `SHOW GRANTS`, `SHOW
/// CREATE TABLE`): one read-only statement.
pub fn check_read(family: CopyFamily, sql: &str) -> Result<()> {
    one_statement(family, sql)?;
    let words = leading_words(sql, 3);
    let w: Vec<&str> = words.iter().map(String::as_str).collect();
    let ok = match w.as_slice() {
        ["SELECT", ..] | ["WITH", ..] => {
            let dialect = match family {
                CopyFamily::Mysql => sqlguard::Dialect::MySql,
                _ => sqlguard::Dialect::Standard,
            };
            sqlguard::check_for(sql, dialect).ok
        }
        ["SHOW", ..] => family == CopyFamily::Mysql,
        ["PRAGMA", ..] => family == CopyFamily::Sqlite && !sql.contains('='),
        _ => false,
    };
    if ok {
        Ok(())
    } else {
        Err(reject(sql, "not a single read-only statement"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use CopyFamily::*;

    fn item(kind: CopyObjectKind, action: PlanAction) -> StmtContext {
        StmtContext::Item { kind, action }
    }

    #[test]
    fn leading_words_skip_comments_and_version_markers() {
        assert_eq!(leading_words("  -- x\n/* y */ create table t (a int)", 3), vec!["CREATE", "TABLE", "T"]);
        assert_eq!(leading_words("/*!50001 CREATE ALGORITHM=UNDEFINED */ /*!50013 DEFINER=`a`@`b` */ VIEW v", 2), vec!["CREATE", "ALGORITHM"]);
        assert_eq!(leading_words("SET @@global.x = 1", 2), vec!["SET", "@@GLOBAL.X"]);
    }

    #[test]
    fn always_rejected_in_every_family() {
        for fam in [Postgres, Mysql, Sqlite] {
            for sql in [
                "SET GLOBAL local_infile = 1",
                "SET PERSIST max_connections = 10",
                "SET PERSIST_ONLY x = 1",
                "SET @@global.sql_mode = ''",
                "SET @@GLOBAL.sql_mode = ''",
                "SET autocommit = 1, GLOBAL max_connections = 5",
                "SET PASSWORD FOR 'u'@'h' = 'x'",
                "SET PASSWORD = 'x'",
                "SET DEFAULT ROLE admin TO 'u'@'h'",
                "SET ROLE admin",
                "SET SESSION AUTHORIZATION bob",
                "SET RESOURCE GROUP big",
                "DROP DATABASE shop",
                "DROP SCHEMA app CASCADE",
                "DROP EXTENSION citext",
                "KILL 42",
                "DELETE FROM t WHERE id = 1",
                "UPDATE t SET a = 1",
                "ALTER SYSTEM SET work_mem = '1GB'",
                "ALTER USER x IDENTIFIED BY 'y'",
                "CREATE USER x",
                "CREATE TABLE a (x int); DROP TABLE b",
            ] {
                assert!(check_statement(fam, sql, item(CopyObjectKind::Table, PlanAction::DropRecreate)).is_err(), "{fam:?}: {sql}");
            }
        }
    }

    #[test]
    fn per_family_allow_lists() {
        let create = item(CopyObjectKind::Table, PlanAction::Create);
        let drop = item(CopyObjectKind::Table, PlanAction::DropRecreate);
        let trunc = item(CopyObjectKind::Table, PlanAction::Truncate);
        // PG
        assert!(check_statement(Postgres, "CREATE TABLE \"a\".\"t\" (id int)", create).is_ok());
        assert!(check_statement(Postgres, "DROP TABLE \"a\".\"t\" RESTRICT", drop).is_ok());
        assert!(check_statement(Postgres, "DROP TABLE \"a\".\"t\" CASCADE", drop).is_err());
        assert!(check_statement(Postgres, "DROP TABLE \"a\".\"t\" RESTRICT", create).is_err(), "drops only for drop_recreate items");
        assert!(check_statement(Postgres, "TRUNCATE ONLY \"a\".\"t\"", trunc).is_ok());
        assert!(check_statement(Postgres, "COPY \"a\".\"t\" (\"id\") FROM STDIN (FORMAT csv)", StmtContext::Load).is_ok());
        assert!(check_statement(Postgres, "COPY \"a\".\"t\" TO STDOUT", StmtContext::Load).is_err());
        assert!(check_statement(Postgres, "SELECT pg_catalog.setval('\"a\".\"s\"', 42, true)", item(CopyObjectKind::SequenceValue, PlanAction::Run)).is_ok());
        assert!(check_statement(Postgres, "SELECT pg_try_advisory_lock(hashtext('bulkdb-copy'))", StmtContext::Lease).is_ok());
        assert!(check_statement(Postgres, "SELECT 1", StmtContext::Session).is_err());
        assert!(check_statement(Postgres, "COMMENT ON TABLE \"t\" IS 'x'", item(CopyObjectKind::Comment, PlanAction::Run)).is_ok());
        assert!(check_statement(Postgres, "INSERT INTO t VALUES (1)", create).is_err());
        assert!(check_statement(Postgres, "CREATE DATABASE x", create).is_err());
        // MySQL
        assert!(check_statement(Mysql, "CREATE DATABASE `shop` DEFAULT CHARACTER SET utf8mb4", item(CopyObjectKind::Database, PlanAction::Create)).is_ok());
        assert!(check_statement(Mysql, "CREATE DATABASE `shop`", create).is_err());
        assert!(check_statement(Mysql, "TRUNCATE TABLE `db`.`t`", trunc).is_ok());
        assert!(check_statement(Mysql, "TRUNCATE `db`.`t`", trunc).is_err());
        assert!(check_statement(Mysql, "DROP TABLE `db`.`t`", drop).is_ok());
        assert!(check_statement(Mysql, "LOAD DATA LOCAL INFILE 'bulkdb-j-1-0' INTO TABLE `db`.`t`", StmtContext::Load).is_ok());
        assert!(check_statement(Mysql, "LOAD DATA LOCAL INFILE '/etc/passwd' INTO TABLE `db`.`t`", StmtContext::Load).is_err());
        assert!(check_statement(Mysql, "SELECT GET_LOCK('bulkdb-copy:ab', 0)", StmtContext::Lease).is_ok());
        assert!(check_statement(Mysql, "ANALYZE TABLE `db`.`t`", item(CopyObjectKind::Analyze, PlanAction::Run)).is_ok());
        assert!(check_statement(Mysql, "SET SESSION sql_mode = 'STRICT_ALL_TABLES'", StmtContext::Session).is_ok());
        // SQLite
        assert!(check_statement(Sqlite, "DELETE FROM \"t\"", trunc).is_ok());
        assert!(check_statement(Sqlite, "DELETE FROM \"t\" WHERE 1", trunc).is_err());
        assert!(check_statement(Sqlite, "DELETE FROM \"t\"", create).is_err());
        assert!(check_statement(Sqlite, "UPDATE sqlite_sequence SET seq = max(seq, 42) WHERE name = 't'", item(CopyObjectKind::SequenceValue, PlanAction::Run)).is_ok());
        assert!(check_statement(
            Sqlite,
            "INSERT INTO sqlite_sequence(name, seq) SELECT 't', 42 WHERE NOT EXISTS (SELECT 1 FROM sqlite_sequence WHERE name = 't')",
            item(CopyObjectKind::SequenceValue, PlanAction::Run)
        )
        .is_ok());
        assert!(check_statement(Sqlite, "INSERT INTO \"t\" (\"a\") VALUES (?)", StmtContext::Load).is_ok());
        assert!(check_statement(Sqlite, "TRUNCATE TABLE t", trunc).is_err());
    }

    #[test]
    fn session_context_is_set_and_tx_only() {
        // SET (session scope) and transaction control are the only session statements.
        assert!(check_statement(Mysql, "SET SESSION sql_mode = 'STRICT_ALL_TABLES'", StmtContext::Session).is_ok());
        assert!(check_statement(Postgres, "SET search_path = \"a\"", StmtContext::Session).is_ok());
        assert!(check_statement(Postgres, "BEGIN", StmtContext::Session).is_ok());
        assert!(check_statement(Mysql, "COMMIT", StmtContext::Session).is_ok());
        // CREATE / ALTER / DROP / DELETE / SELECT must not slip through a session.
        for sql in ["CREATE TABLE \"t\" (a int)", "ALTER TABLE \"t\" ADD c int", "DROP TABLE \"t\" RESTRICT", "SELECT 1", "TRUNCATE \"t\""] {
            assert!(check_statement(Postgres, sql, StmtContext::Session).is_err(), "session: {sql}");
        }
    }

    #[test]
    fn truncate_and_delete_only_for_their_items() {
        let trunc = item(CopyObjectKind::Table, PlanAction::Truncate);
        let group = item(CopyObjectKind::TruncateGroup, PlanAction::Run);
        // TRUNCATE: a table-truncate item or a truncate-group Run item, never a load or other item.
        assert!(check_statement(Postgres, "TRUNCATE ONLY \"a\".\"t\"", trunc).is_ok());
        assert!(check_statement(Postgres, "TRUNCATE \"a\".\"t1\", \"a\".\"t2\"", group).is_ok());
        assert!(check_statement(Mysql, "TRUNCATE TABLE `db`.`t`", group).is_ok());
        assert!(check_statement(Postgres, "TRUNCATE \"a\".\"t\"", StmtContext::Load).is_err(), "no TRUNCATE on a load session");
        assert!(check_statement(Postgres, "TRUNCATE \"a\".\"t\"", item(CopyObjectKind::Table, PlanAction::Create)).is_err());
        assert!(check_statement(Postgres, "TRUNCATE \"a\".\"t\"", item(CopyObjectKind::Table, PlanAction::DropRecreate)).is_err());
        assert!(check_statement(Postgres, "TRUNCATE \"a\".\"t\"", item(CopyObjectKind::Analyze, PlanAction::Run)).is_err(), "an Analyze item must not truncate");
        assert!(check_statement(Postgres, "TRUNCATE \"a\".\"t\"", item(CopyObjectKind::Comment, PlanAction::Run)).is_err());
        // SQLite DELETE: only a table-truncate item, never a load.
        assert!(check_statement(Sqlite, "DELETE FROM \"t\"", trunc).is_ok());
        assert!(check_statement(Sqlite, "DELETE FROM \"t\"", StmtContext::Load).is_err(), "no DELETE on a load session");
        assert!(check_statement(Sqlite, "DELETE FROM \"t\"", item(CopyObjectKind::Table, PlanAction::DropRecreate)).is_err());
    }

    #[test]
    fn dry_run_list() {
        assert!(check_statement(Postgres, "CREATE TABLE t (a int)", StmtContext::DryRun).is_ok());
        assert!(check_statement(Postgres, "SAVEPOINT s1", StmtContext::DryRun).is_ok());
        assert!(check_statement(Postgres, "ROLLBACK TO SAVEPOINT s1", StmtContext::DryRun).is_ok());
        for sql in [
            "TRUNCATE t",
            "DROP TABLE t RESTRICT",
            "SELECT pg_catalog.setval('s', 1, true)",
            "COPY t FROM STDIN",
            "SET GLOBAL x = 1",
            "DROP SCHEMA s",
            "DELETE FROM t",
            "ANALYZE t",
        ] {
            assert!(check_statement(Postgres, sql, StmtContext::DryRun).is_err(), "{sql}");
        }
        assert!(check_statement(Mysql, "CREATE TABLE t (a int)", StmtContext::DryRun).is_err(), "MySQL dry runs execute nothing");
    }

    #[test]
    fn reads() {
        assert!(check_read(Mysql, "SHOW WARNINGS LIMIT 10").is_ok());
        assert!(check_read(Mysql, "SELECT 1 FROM `db`.`t` LIMIT 1").is_ok());
        assert!(check_read(Postgres, "SELECT EXISTS (SELECT 1 FROM ONLY \"a\".\"t\")").is_ok());
        assert!(check_read(Postgres, "SHOW work_mem").is_err());
        assert!(check_read(Sqlite, "PRAGMA table_info(\"t\")").is_ok());
        assert!(check_read(Sqlite, "PRAGMA journal_mode = WAL").is_err());
        assert!(check_read(Mysql, "SELECT 1; SELECT 2").is_err());
        assert!(check_read(Postgres, "DELETE FROM t").is_err());
    }
}
